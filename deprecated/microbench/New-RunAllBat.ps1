#requires -version 5.1
<#
Creates runall.bat with NO labels, NO CALL, NO FOR, NO GOTO in the .BAT itself.
Instead, this PowerShell script expands the runs (RUNS_PER_EXE) by emitting repeated
blocks for each EXE.

Matrix:
  -O2/-O3/-Os x {arch_none, arch_gracemont, arch_raptorlake}
Arch rule:
  arch=none       => (no -march, no -mtune)
  arch=gracemont  => -march=gracemont  -mtune=gracemont
  arch=raptorlake => -march=raptorlake -mtune=raptorlake

Usage:
  powershell -ExecutionPolicy Bypass -File .\New-RunAllBat.ps1
Then:
  runall.bat > results.txt
#>

param(
    [string]$OutDir  = 'build',
    [string]$BatPath = 'runall.bat',

    # How many times to run each EXE (emitted as repeated blocks in the BAT)
    [int]$RunsPerExe = 5
)

Set-StrictMode -Off
$ErrorActionPreference = 'Stop'

$optLevels   = @('O2', 'O3', 'Os')
$archTargets = @('', 'gracemont', 'raptorlake')  # '' => none

function ArchLabel([string]$arch) {
    if ([string]::IsNullOrWhiteSpace($arch)) { return 'arch_none' }
    return "arch_$arch"
}

if ($RunsPerExe -lt 1) { $RunsPerExe = 1 }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('@echo off')
$lines.Add('setlocal enableextensions')
$lines.Add('')
$lines.Add('rem Auto-generated by New-RunAllBat.ps1 (NO labels/call/for/goto)')
$lines.Add(('set "OUTDIR={0}"' -f $OutDir))
$lines.Add('')
$lines.Add('rem ---- Runtime controls you may edit ----')
$lines.Add('rem If you want logical CPU #26, affinity bitmask is 1<<26 = 0x04000000')
$lines.Add('set "AFFINITY_MASK_HEX=04000000"')
$lines.Add('set "AFFINITY_MASK_ARG=0x04000000"')
$lines.Add('rem Priority switch for START (use /high by default; /realtime is risky)')
$lines.Add('set "PRIORITY_SWITCH=/high"')
$lines.Add('')
$lines.Add('rem ---- Bench arguments ----')
$lines.Add('set "SLEEP_MS=0"')
$lines.Add('set "BENCH_ITERS=1000000"')
$lines.Add('set "BENCH_WARMUP=100000"')
$lines.Add('set "REPORT_EVERY=1000"')
$lines.Add('set "DT_MS=1"')
$lines.Add('set "EXTRA_ARGS=--no-console-banner"')
$lines.Add('')
$lines.Add('echo [runall] OUTDIR=%OUTDIR%')
$lines.Add('echo [runall] AFFINITY_MASK_HEX=%AFFINITY_MASK_HEX%  AFFINITY_MASK_ARG=%AFFINITY_MASK_ARG%')
$lines.Add('echo [runall] PRIORITY_SWITCH=%PRIORITY_SWITCH%')
$lines.Add(('echo [runall] RUNS_PER_EXE={0}' -f $RunsPerExe))
$lines.Add('echo [runall] bench args: --bench --monitor-gas --monitor-clutch --sleep %SLEEP_MS% --bench-iters %BENCH_ITERS% --bench-warmup %BENCH_WARMUP% --bench-report-every %REPORT_EVERY% --bench-dt-ms %DT_MS% --affinitymask %AFFINITY_MASK_ARG% %EXTRA_ARGS%')
$lines.Add('echo [runall] Matrix: -O{2,3,s} x {arch_none, arch_gracemont, arch_raptorlake} (march==mtune when present)')
$lines.Add('echo.')

foreach ($o in $optLevels) {
    foreach ($arch in $archTargets) {

        $archLabel = ArchLabel $arch
        $exeName = "bench_${o}_${archLabel}.exe"
        $exeRel  = "%OUTDIR%\$exeName"
        $archDisp = if ($arch) { $arch } else { 'none' }

        for ($r = 1; $r -le $RunsPerExe; $r++) {

            $lines.Add('')
            $lines.Add(("set ""EXE={0}""" -f $exeRel))
            $lines.Add(("echo ===RUN=== exe=%EXE% O={0} march={1} mtune={1} run={2}" -f $o, $archDisp, $r))
            $lines.Add('if not exist "%EXE%" (')
            $lines.Add('  echo ===MISSING=== %EXE%')
            $lines.Add(') else (')
            $lines.Add('  start "" /b /wait %PRIORITY_SWITCH% /affinity %AFFINITY_MASK_HEX% "%EXE%" --bench --monitor-gas --monitor-clutch --sleep %SLEEP_MS% --bench-iters %BENCH_ITERS% --bench-warmup %BENCH_WARMUP% --bench-report-every %REPORT_EVERY% --bench-dt-ms %DT_MS% --affinitymask %AFFINITY_MASK_ARG% %EXTRA_ARGS%')
            $lines.Add(')')
            $lines.Add(("echo ===ENDRUN=== exe=%EXE% O={0} march={1} mtune={1} run={2}" -f $o, $archDisp, $r))
            $lines.Add('echo.')
        }
    }
}

$lines.Add('echo [runall] done.')
$lines.Add('endlocal')
$lines.Add('exit /b 0')

Set-Content -Path $BatPath -Value $lines -Encoding ASCII
Write-Host "Wrote $BatPath"