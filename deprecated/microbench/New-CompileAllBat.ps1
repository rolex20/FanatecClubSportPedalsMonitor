#requires -version 5.1
<#
Creates compileall.bat building ONLY these arch pairings:
  arch=none       => (no -march, no -mtune)
  arch=gracemont  => -march=gracemont  -mtune=gracemont
  arch=raptorlake => -march=raptorlake -mtune=raptorlake

Optimization levels:
  -O2, -O3, -Os

Outputs EXEs into .\build\

Usage:
  powershell -ExecutionPolicy Bypass -File .\New-CompileAllBat.ps1
#>

param(
    [string]$GccPath = 'C:\msys64\ucrt64\bin\gcc.exe',
    [string]$Source  = 'main.c',
    [string]$OutDir  = 'build',
    [string]$BatPath = 'compileall.bat'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$optLevels = @('O2', 'O3', 'Os')
$archTargets = @('', 'gracemont', 'raptorlake')  # '' => none

function ArchLabel([string]$arch) {
    if ([string]::IsNullOrWhiteSpace($arch)) { return 'arch_none' }
    return "arch_$arch"
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('@echo off')
$lines.Add('setlocal enableextensions enabledelayedexpansion')
$lines.Add('')
$lines.Add('rem Auto-generated by New-CompileAllBat.ps1')
$lines.Add(('set "GCC={0}"' -f $GccPath))
$lines.Add(('set "SRC={0}"' -f $Source))
$lines.Add(('set "OUTDIR={0}"' -f $OutDir))
$lines.Add('set "BASE=-s -m64 -std=c11"')
$lines.Add('')
$lines.Add('if not exist "%OUTDIR%" mkdir "%OUTDIR%"')
$lines.Add('echo [compileall] GCC=%GCC%')
$lines.Add('echo [compileall] SRC=%SRC%')
$lines.Add('echo [compileall] OUTDIR=%OUTDIR%')
$lines.Add('echo [compileall] Matrix: -O{2,3,s} x {arch_none, arch_gracemont, arch_raptorlake}')
$lines.Add('echo.')
$lines.Add('set "FAIL=0"')
$lines.Add('')

foreach ($o in $optLevels) {
    foreach ($arch in $archTargets) {

        $archLabel = ArchLabel $arch
        $exeName = "bench_${o}_${archLabel}.exe"

        $oFlag = "-$o"
        $marchFlag = if ($arch) { "-march=$arch" } else { "" }
        $mtuneFlag = if ($arch) { "-mtune=$arch" } else { "" }

        $dispArch = if ($arch) { $arch } else { 'none' }

        $lines.Add(('echo [compile] {0}  {1}  arch={2}' -f $exeName, $oFlag, $dispArch))
        $cmd = '"%GCC%" %BASE% {0} {1} {2} "%SRC%" -o "%OUTDIR%\{3}" -lwinmm' -f $oFlag, $marchFlag, $mtuneFlag, $exeName
        $lines.Add($cmd.Trim())
        $lines.Add('if errorlevel 1 (echo [FAIL] ' + $exeName + ' & set "FAIL=1") else (echo [ OK ] ' + $exeName + ')')
        $lines.Add('echo.')
    }
}

$lines.Add('if "%FAIL%"=="1" (')
$lines.Add('  echo One or more builds FAILED.')
$lines.Add('  exit /b 1')
$lines.Add(') else (')
$lines.Add('  echo All builds succeeded.')
$lines.Add('  exit /b 0')
$lines.Add(')')
$lines.Add('endlocal')

Set-Content -Path $BatPath -Value $lines -Encoding ASCII
Write-Host "Wrote $BatPath"
